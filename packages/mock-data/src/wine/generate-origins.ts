/**
 * Origin and varietal statistics for the synthetic wine generator (`./generate.ts`): every
 * country → province → region → subregion leaf, every varietal, and how often each varietal appears
 * in each leaf.
 *
 * @remarks
 * **What this is.** Aggregate counts measured from the public Kaggle "Wine Reviews" dataset
 * (129,907 reviews): 1,619 origin leaves, 701 varietals and the
 * 9,663 non-empty (leaf, varietal) cells between them. Place names and grape names are facts; the
 * counts are statistics. No review text, wine title, winery name or taster name is included, and
 * no record of the dataset can be reconstructed from these tables.
 *
 * **How the generator uses it.** Each cell's count becomes its share of the full tier: the
 * generator apportions {@link FULL_WINE_TIER_SIZE} records across the cells by largest remainder,
 * so at full-tier size every leaf and every varietal appears at its measured share, and none is
 * missing. Because the full tier is larger than the measured total, every cell, however rare,
 * receives at least one record.
 *
 * **Colors.** A varietal's color comes from its name (Rosé, Sparkling Blend, Port), from a curated
 * grape list, or from the vocabulary of the reviews written about it. A cell carries its own color
 * when the place overrides the grape: Chardonnay from Champagne is sparkling, Sémillon from
 * Sauternes is a dessert wine.
 *
 * @packageDocumentation
 */

import type { WineColor } from './types.js';

/**
 * One varietal: its name, its usual color, and two adjustments the generator applies to every
 * record of it.
 *
 * - `pointsShift` — the varietal's score lean, in standard-normal units, after its countries'
 *   leans are accounted for (Nebbiolo scores above the average; a bulk grape below it).
 * - `logPriceOffset` — its natural-log price lean at a given score and country.
 *
 * Both are shrunk toward zero for rare varietals, so a grape seen a handful of times keeps a
 * near-average score and price instead of inheriting its few reviews' noise.
 */
export type WineVarietalRow = readonly [name: string, color: WineColor, pointsShift: number, logPriceOffset: number];

/**
 * One origin leaf and its varietal mix.
 *
 * `cells` is a space-separated list of `varietalIndex:count` pairs, where `varietalIndex`
 * indexes {@link WINE_VARIETAL_ROWS}. A third field (`:s`, `:d`, `:f`) overrides the
 * varietal's color for that cell with sparkling, dessert or fortified. Empty `region` and
 * `subregion` strings are levels the place does not have.
 */
export type WineOriginLeafRow = readonly [country: string, province: string, region: string, subregion: string, cells: string];

