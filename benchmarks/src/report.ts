/**
 * Report rendering — turns completed tinybench `Task` results into a committed Markdown report
 * (tables + ASCII bars) and a machine-readable JSON export. Pure formatting; all file IO lives
 * in `run.ts`. tinybench v6 exposes per-task latency statistics under `task.result.latency`
 * (mean in milliseconds, `moe`/`rme` for the 95% margin of error, `samples` for the run count).
 *
 * @packageDocumentation
 */
import type { Task } from 'tinybench';

/** A single measured cell — one matrix combo's latency statistics. */
export interface BenchOutcome {
	readonly cellLabel: string;
	readonly meanMs: number;
	readonly rmePct: number;
	readonly samples: number;
}

/** All cells measured for one scenario at one corpus tier. */
export interface ScenarioReport {
	readonly outcomes: readonly BenchOutcome[];
	readonly scenarioId: string;
	readonly scenarioTitle: string;
	readonly tierName: string;
}

const BAR_WIDTH = 32;

/** Extract the latency statistics from a completed tinybench task. */
export function outcomeFromTask(cellLabel: string, task: Task): BenchOutcome {
	// tinybench's `result` is a union — latency stats exist only on a completed (non-aborted) run.
	const result = task.result;
	const latency = 'latency' in result ? result.latency : undefined;

	return {
		cellLabel,
		meanMs: latency?.mean ?? Number.NaN,
		rmePct: latency?.rme ?? Number.NaN,
		samples: latency?.samplesCount ?? 0,
	};
}

/**
 * Name every cell that produced no measurement — a non-finite mean or zero samples — as
 * `<scenario> @ <tier>: <cell>`.
 *
 * @remarks
 * A cell whose function throws is not timed: tinybench records the error, and
 * {@link outcomeFromTask} reads it as a `NaN` mean over 0 samples. Rendered, that is one more table
 * row, easy to miss among the others and easy to commit. The runner refuses to write a report while
 * this list is non-empty.
 *
 * @param reports - Every scenario/tier report of a run.
 * @returns The unmeasured cells, in report order; empty when every cell has a number.
 */
export function unmeasuredCells(reports: readonly ScenarioReport[]): readonly string[] {
	return reports.flatMap((report) =>
		report.outcomes
			.filter((outcome) => !Number.isFinite(outcome.meanMs) || outcome.samples === 0)
			.map((outcome) => `${report.scenarioId} @ ${report.tierName}: ${outcome.cellLabel}`));
}

/** Render an ASCII bar sized relative to `max` (the slowest cell in the group). */
function bar(value: number, max: number): string {
	if (!Number.isFinite(value) || !Number.isFinite(max) || max <= 0) {
		return '░'.repeat(BAR_WIDTH);
	}
	const filled = Math.min(BAR_WIDTH, Math.max(1, Math.round((value / max) * BAR_WIDTH)));

	return '█'.repeat(filled) + '░'.repeat(BAR_WIDTH - filled);
}

/** Render one scenario/tier section: a heading, a stats table, and relative-speed bars. */
function renderScenario(report: ScenarioReport): string {
	const slowest = report.outcomes.reduce((max, o) => (o.meanMs > max ? o.meanMs : max), 0);
	const fastest = report.outcomes.reduce(
		(min, o) => (Number.isFinite(o.meanMs) && o.meanMs < min ? o.meanMs : min),
		Number.POSITIVE_INFINITY,
	);
	const lines = [
		`### ${report.scenarioTitle} — ${report.tierName}`,
		'',
		'| Cell | Mean | ± 95% CI | Samples | Relative |',
		'| :--- | ---: | ---: | ---: | :--- |',
	];

	for (const outcome of report.outcomes) {
		const relative =
			Number.isFinite(fastest) && fastest > 0 && Number.isFinite(outcome.meanMs)
				? `${(outcome.meanMs / fastest).toFixed(1)}×`
				: '—';

		lines.push(
			`| \`${outcome.cellLabel}\` | ${outcome.meanMs.toFixed(4)} ms | ±${outcome.rmePct.toFixed(1)}% `
			+ `| ${outcome.samples} | \`${bar(outcome.meanMs, slowest)}\` ${relative} |`,
		);
	}
	lines.push('');

	return lines.join('\n');
}

/** Render the full Markdown report. */
export function renderMarkdown(reports: readonly ScenarioReport[]): string {
	const header = [
		'# Filter EngineZ — Benchmark Results',
		'',
		'> Generated by `pnpm bench:write` (tinybench).',
		'> Mean latency ± 95% relative margin of error; lower is faster. `filter-intersection`',
		'> compares a fresh predicate pass (`applyFiltersAndQuery`) against the Roaring-Bitmap path',
		'> (`computeResults`).',
		'',
	];
	const body = reports.map(renderScenario);

	return [...header, ...body, ''].join('\n');
}

/** Render the machine-readable JSON export. */
export function renderJson(reports: readonly ScenarioReport[]): string {
	return `${JSON.stringify({ generatedAt: new Date().toISOString(), reports }, null, 2)}\n`;
}
